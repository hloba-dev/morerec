/**
 * Приводит текст из буфера обмена к виду, пригодному для поля номера.
 * Убирает переносы строк, сворачивает пробелы, обрезает края.
 * Формат самого номера (пробелы в карте, «+» и дефисы в телефоне) не трогаем —
 * это ровно то, что пользователь вставил бы вручную.
 */
export function normalizePasted(raw: string): string {
  return (raw ?? '').replace(/\s+/g, ' ').trim();
}
